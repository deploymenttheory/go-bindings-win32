package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	rawwin "github.com/deploymenttheory/go-bindings-win32/internal/codegen/emit/raw"
)

// The coverage report: what the generator emitted versus what the metadata
// declares, and why the rest was not — written by `generate bindings
// --coverage docs/COVERAGE.md` from the same run that produced the tree, so
// it can never describe a different tree than the one committed.

// diagnosticClasses classify every diagnostic the generator can produce.
// Order matters: the first matching class wins.
var diagnosticClasses = []struct {
	name    string
	skip    bool // a construct was not emitted (vs. an informational note)
	pattern *regexp.Regexp
}{
	{"function or method skipped: parameter not marshalable", true, regexp.MustCompile(`param .* not marshalable`)},
	{"function or method skipped: return not marshalable", true, regexp.MustCompile(`return (with SetLastError )?not marshalable`)},
	{"function skipped: not a DLL export and no [Constant]", true, regexp.MustCompile(`not a loadable module`)},
	{"struct skipped: no amd64 layout", true, regexp.MustCompile(`no amd64 variant, skipped`)},
	{"struct or union skipped: layout not computable", true, regexp.MustCompile(`layout not computable|type unresolved, struct skipped`)},
	{"struct note: architecture-specific layouts, amd64 emitted", false, regexp.MustCompile(`emitting amd64 variant only`)},
	{"handle closer not emitted", true, regexp.MustCompile(`no closer|closer name .* already used`)},
	{"name collision: construct dropped", true, regexp.MustCompile(`name already used|IID name .* already used|Procs table name`)},
	{"name collision: -W suffix kept", false, regexp.MustCompile(`bare name .* taken, keeping`)},
	{"constant skipped: initializer not representable", true, regexp.MustCompile(`^constant `)},
	{"cross-namespace reference degraded (import cycle)", false, regexp.MustCompile(`cycle break`)},
	{"reference to a skipped type degraded", false, regexp.MustCompile(`reference to skipped type`)},
	{"interface skipped: unresolvable base chain", true, regexp.MustCompile(`unresolvable base chain`)},
	{"interface note: base not embedded (import cycle)", false, regexp.MustCompile(`not embedded`)},
	{"curated entry did not match (stale)", false, regexp.MustCompile(`stale entry`)},
	{"informational-success annotation not applied", false, regexp.MustCompile(`annotation not applied`)},
}

var notMarshalableType = regexp.MustCompile(`not marshalable \(([^)]+)\)`)

// writeCoverage renders the report to path.
func writeCoverage(path, winmdVersion string, coverage []rawwin.NamespaceCoverage, diagnostics []string) error {
	var totals rawwin.NamespaceCoverage
	for _, entry := range coverage {
		totals.Functions += entry.Functions
		totals.FunctionsEmitted += entry.FunctionsEmitted
		totals.Methods += entry.Methods
		totals.MethodsEmitted += entry.MethodsEmitted
		totals.Structs += entry.Structs
		totals.StructsEmitted += entry.StructsEmitted
		totals.Closers += entry.Closers
		totals.ClosersEmitted += entry.ClosersEmitted
	}

	classCounts := make([]int, len(diagnosticClasses))
	other := 0
	typeCounts := map[string]int{}
	for _, diagnostic := range diagnostics {
		matched := false
		for i, class := range diagnosticClasses {
			if class.pattern.MatchString(diagnostic) {
				classCounts[i]++
				matched = true
				break
			}
		}
		if !matched {
			other++
		}
		if m := notMarshalableType.FindStringSubmatch(diagnostic); m != nil {
			typeCounts[m[1]]++
		}
	}

	var b strings.Builder
	b.WriteString("# Coverage\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/generate bindings --coverage docs/COVERAGE.md`; do not edit. -->\n\n")
	fmt.Fprintf(&b, "Generated from `Microsoft.Windows.SDK.Win32Metadata` **%s** (`metadata/winmd/Windows.Win32.winmd`).\n\n", winmdVersion)
	b.WriteString("Everything the metadata declares is emitted unless a diagnostic below says\n")
	b.WriteString("otherwise; the diagnostics are ratcheted in CI (`metadata/diagnostics-baseline.json`).\n\n")
	b.WriteString("## Totals\n\n")
	b.WriteString("| Construct | Emitted | Declared | Coverage |\n|---|---:|---:|---:|\n")
	row := func(name string, emitted, total int) {
		fmt.Fprintf(&b, "| %s | %d | %d | %s |\n", name, emitted, total, percent(emitted, total))
	}
	row("Namespaces (packages)", len(coverage), len(coverage))
	row("Functions", totals.FunctionsEmitted, totals.Functions)
	row("COM methods", totals.MethodsEmitted, totals.Methods)
	row("Structs and unions", totals.StructsEmitted, totals.Structs)
	row("Handle closers (`[RAIIFree]`)", totals.ClosersEmitted, totals.Closers)

	b.WriteString("\n## Diagnostics by class\n\n")
	fmt.Fprintf(&b, "%d diagnostics. \"Skip\" classes drop a construct; the others record a degradation or a note.\n\n", len(diagnostics))
	b.WriteString("| Class | Kind | Count |\n|---|---|---:|\n")
	for i, class := range diagnosticClasses {
		if classCounts[i] == 0 {
			continue
		}
		kind := "note"
		if class.skip {
			kind = "skip"
		}
		fmt.Fprintf(&b, "| %s | %s | %d |\n", class.name, kind, classCounts[i])
	}
	if other > 0 {
		fmt.Fprintf(&b, "| (unclassified) | | %d |\n", other)
	}

	if len(typeCounts) > 0 {
		b.WriteString("\n### Types behind the not-marshalable skips\n\n")
		b.WriteString("| Go type | Skips |\n|---|---:|\n")
		types := make([]string, 0, len(typeCounts))
		for name := range typeCounts {
			types = append(types, name)
		}
		sort.Slice(types, func(i, j int) bool {
			if typeCounts[types[i]] != typeCounts[types[j]] {
				return typeCounts[types[i]] > typeCounts[types[j]]
			}
			return types[i] < types[j]
		})
		for _, name := range types {
			fmt.Fprintf(&b, "| `%s` | %d |\n", name, typeCounts[name])
		}
	}

	b.WriteString("\n## Per namespace\n\n")
	b.WriteString("Functions and COM methods emitted / declared; namespaces with no gap are listed for completeness.\n\n")
	b.WriteString("| Namespace | Functions | COM methods | Structs | Closers |\n|---|---:|---:|---:|---:|\n")
	for _, entry := range coverage {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", entry.Namespace,
			ratio(entry.FunctionsEmitted, entry.Functions), ratio(entry.MethodsEmitted, entry.Methods),
			ratio(entry.StructsEmitted, entry.Structs), ratio(entry.ClosersEmitted, entry.Closers))
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func percent(emitted, total int) string {
	if total == 0 {
		return "—"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(emitted)/float64(total))
}

func ratio(emitted, total int) string {
	if total == 0 {
		return "—"
	}
	if emitted == total {
		return fmt.Sprintf("%d", total)
	}
	return fmt.Sprintf("%d / %d", emitted, total)
}
